import argparse
import contextlib
import io
import json
import tempfile
import unittest
from pathlib import Path
from unittest import mock

from osgeo import gdal

from config import grid, stack
from pipeline.phase2_build import build_scores, provenance
from pipeline.phase2_build.tests.fixtures import source_fixture, v1_manifest_fixture
from scoring.tests.fixtures import write_fixture


class CandidateBuildTests(unittest.TestCase):
    """Tiny mocked dimensions exercise the complete workflow, not real inputs."""

    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix="phase2-builder-", dir="/tmp/opencode")
        self.root = Path(self.temporary.name)
        self.patches = [mock.patch.object(build_scores, "ROOT", self.root), mock.patch.object(grid, "COLS", 11), mock.patch.object(grid, "ROWS", 9)]
        for patch in self.patches:
            patch.start()
        paths = write_fixture(self.root)
        processed = self.root / "data/processed"
        processed.mkdir(parents=True)
        source_path = processed / "common_stack_v1.tif"
        source = source_fixture()
        copied = gdal.Translate(str(source_path), source, format="COG", creationOptions=["COMPRESS=DEFLATE", "PREDICTOR=FLOATING_POINT",
            f"BLOCKSIZE={stack.BLOCK_SIZE}", "OVERVIEWS=FORCE_USE_EXISTING", "NUM_THREADS=1"])
        source = copied = None
        lookup_path = processed / "woreda_id_lookup.csv"
        lookup_path.write_text("raster_id,name\n1,Synthetic\n")
        anchor = self.root / "anchor.txt"
        anchor.write_text("Synthetic accepted provenance\n")
        unused = self.root / "data/inputs/unused-native.bin"
        unused.parent.mkdir(parents=True)
        unused.write_bytes(b"Never read or regenerated by scoring")
        self.v1 = v1_manifest_fixture()
        self.v1.update({"raster_file": provenance.label(source_path, self.root), "raster_sha256": provenance.sha256(source_path),
            "raster_size_bytes": source_path.stat().st_size, "build_inputs": provenance.fingerprints([anchor], self.root),
            "lookup": {"file": provenance.label(lookup_path, self.root), "sha256": provenance.sha256(lookup_path), "rows": 1},
            "storage": {"compression": "DEFLATE", "predictor": 3, "physical_dtype": "float32", "nodata": grid.NODATA,
                        "block_size": [stack.BLOCK_SIZE, stack.BLOCK_SIZE], "continuous_overviews": "average", "categorical_id_mask_overviews": "mode"}})
        manifest_path = processed / "band_manifest.json"
        manifest_path.write_text(json.dumps(self.v1, indent=1) + "\n", encoding="utf-8")
        self.original_manifest = manifest_path.read_bytes()
        validation_path = processed / "stack_v1_validation.json"
        provenance.write_json(validation_path, {"status": "passed", "stack_version": 1, "core_bands": 38,
            "raster_sha256": self.v1["raster_sha256"], "all_original_inputs_unchanged": True,
            "geographic_checks": {"sites": {"Addis Ababa": {"common_grid_row": 1, "common_grid_col": 1},
                                            "Danakil/Dallol diagnostic site": {"common_grid_row": 2, "common_grid_col": 2}}}})
        self.scripts = (self.root / "pipeline/grid.yaml", self.root / "pipeline/phase2_build/build_scores.py")
        for path in self.scripts:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text("# Synthetic provenance fixture; production grid is untouched\n")
        self.args = argparse.Namespace(source_stack=source_path, source_manifest=manifest_path, v1_validation=validation_path,
            soil_thresholds=paths["soil_path"], crops=paths["crops_path"], crop_requirements=paths["requirements_path"],
            params=paths["params_path"], work_dir=self.root / "data/interim/score_build")

    def tearDown(self):
        for patch in reversed(self.patches):
            patch.stop()
        self.temporary.cleanup()

    def build(self):
        with mock.patch.object(build_scores, "code_files", return_value=self.scripts), contextlib.redirect_stdout(io.StringIO()):
            return build_scores.build(self.args)

    def test_complete_candidate_build_preserves_v1_and_never_promotes(self):
        report = self.build()
        self.assertEqual(report["status"], "awaiting_owner_review")
        self.assertEqual(report["technical"]["status"], "passed")
        self.assertGreaterEqual(report["technical"]["scalar_checks"]["compared_cells"], 32)
        self.assertEqual(report["reproducibility"]["status"], "byte_identical")
        self.assertTrue(report["reproducibility"]["raw_assembly_bytes_equal"])
        self.assertEqual(self.args.source_manifest.read_bytes(), self.original_manifest)
        self.assertEqual((self.args.work_dir / "band_manifest_v1.json").read_bytes(), self.original_manifest)
        self.assertEqual(provenance.sha256(self.args.source_stack), self.v1["raster_sha256"])
        manifest = provenance.load_json(self.args.work_dir / "band_manifest.json")
        self.assertEqual(manifest["bands"][:38], self.v1["bands"])
        self.assertEqual(len(manifest["bands"]), 52)
        self.assertFalse((self.root / "data/processed/common_stack_v2.tif").exists())
        self.assertIn("candidate only", (self.args.work_dir / "score_build_report.md").read_text())
        unchanged = {path.relative_to(self.root).as_posix(): (path.stat().st_size, path.stat().st_mtime_ns)
                     for path in self.root.rglob("*") if path.is_file()}
        result = build_scores.validate_only(self.args.work_dir)
        self.assertEqual(result["status"], "passed_read_only")
        self.assertEqual(result["band_count"], 52)
        self.assertEqual(unchanged, {path.relative_to(self.root).as_posix(): (path.stat().st_size, path.stat().st_mtime_ns)
                                     for path in self.root.rglob("*") if path.is_file()})

    def test_rerunning_owned_step_is_byte_identical(self):
        self.build()
        first = (self.args.work_dir / "band_manifest.json").read_bytes()
        first_hash = provenance.sha256(self.args.work_dir / "common_stack_v2.tif")
        self.build()
        self.assertEqual((self.args.work_dir / "band_manifest.json").read_bytes(), first)
        self.assertEqual(provenance.sha256(self.args.work_dir / "common_stack_v2.tif"), first_hash)
        self.assertEqual(self.args.source_manifest.read_bytes(), self.original_manifest)

    def test_invalid_phase1_acceptance_fails_before_claiming_outputs(self):
        validation = provenance.load_json(self.args.v1_validation)
        validation["status"] = "failed"
        provenance.write_json(self.args.v1_validation, validation)
        with self.assertRaisesRegex(ValueError, "acceptance evidence"):
            self.build()
        self.assertFalse((self.args.work_dir / "build_state.json").exists())
        self.assertEqual(self.args.source_manifest.read_bytes(), self.original_manifest)

    def test_changed_scoring_input_invalidates_read_only_acceptance(self):
        self.build()
        candidate = self.args.work_dir / "common_stack_v2.tif"
        before = provenance.sha256(candidate)
        self.args.params.write_text(self.args.params.read_text() + "# owner edited configuration\n")
        with self.assertRaisesRegex(ValueError, "checksum/size mismatch"):
            build_scores.validate_only(self.args.work_dir)
        self.assertEqual(provenance.sha256(candidate), before)

    def test_unfamiliar_output_is_not_overwritten(self):
        self.args.work_dir.mkdir(parents=True)
        output = self.args.work_dir / "common_stack_v2.tif"
        output.write_text("user work")
        with self.assertRaisesRegex(ValueError, "no known owner"):
            self.build()
        self.assertEqual(output.read_text(), "user work")

    def test_protected_input_cannot_overlap_atomic_write_scratch(self):
        work, managed = provenance.check_workspace(self.args.work_dir, self.root, code_files=self.scripts)
        provenance.begin_workspace(work, managed)
        before = (work / provenance.STATE_FILE).read_bytes()
        scratch = work / "band_manifest.json.tmp"
        scratch.write_bytes(self.args.params.read_bytes())
        self.args.params = scratch
        with self.assertRaisesRegex(ValueError, "protected source input"):
            self.build()
        self.assertEqual((work / provenance.STATE_FILE).read_bytes(), before)
        self.assertEqual(scratch.read_bytes(), (self.root / "params.yaml").read_bytes())

    def test_conflicting_archive_does_not_replace_workspace_state(self):
        work, managed = provenance.check_workspace(self.args.work_dir, self.root, code_files=self.scripts)
        provenance.begin_workspace(work, managed)
        state = (work / provenance.STATE_FILE).read_bytes()
        archive = work / "band_manifest_v1.json"
        archive.write_bytes(b"Unfamiliar archive")
        with self.assertRaisesRegex(ValueError, "archive differs"):
            self.build()
        self.assertEqual((work / provenance.STATE_FILE).read_bytes(), state)
        self.assertEqual(archive.read_bytes(), b"Unfamiliar archive")

    def test_modified_review_report_invalidates_read_only_acceptance(self):
        self.build()
        report = self.args.work_dir / "score_build_report.json"
        report.write_text(report.read_text() + "\n")
        with self.assertRaisesRegex(ValueError, "changed outside"):
            build_scores.validate_only(self.args.work_dir)
